package assembly

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

const modulePath = "github.com/zenmark-org/zenmd"

// pluginPackages maps a built-in plugin id to its package; the generated code
// imports (and so links) only the ones an assembly lists.
var pluginPackages = map[string]string{
	"codeblock": "builtins/plugins/codeblock",
	"diagram":   "builtins/plugins/diagram",
	"check":     "builtins/plugins/check",
	"quiz":      "builtins/plugins/quiz",
	"sandbox":   "builtins/plugins/sandbox",
}

// dialectPackages maps a built-in dialect id to its package.
var dialectPackages = map[string]string{
	"myst": "builtins/dialects/myst",
}

// Generate returns the Go file (assembly_gen.go, in the given package) for an
// assembly: the plugins it registers, the layouts and templates it selects and
// its BuildInfo. The assembly must be checked (Load or Check): every id that
// reaches the code is validated here again against the allowed shape and the
// known plugin packages, and nothing else from the assembly is written.
func Generate(a Assembly, pkg string) ([]byte, error) {
	if !ValidID(pkg) && pkg != "main" {
		return nil, fmt.Errorf("package name %q is not valid", pkg)
	}
	for _, kind := range [][]string{{a.App}, {a.Theme}, a.Features, a.Plugins, a.Layouts, a.Templates, a.Dialects} {
		for _, id := range kind {
			if !ValidID(id) {
				return nil, fmt.Errorf("id %q is not valid (want lower case letters, digits and -)", id)
			}
		}
	}
	for _, id := range a.Plugins {
		if _, ok := pluginPackages[id]; !ok {
			return nil, fmt.Errorf("unknown plugin %q", id)
		}
	}

	for _, id := range a.Dialects {
		if _, ok := dialectPackages[id]; !ok {
			return nil, fmt.Errorf("unknown dialect %q", id)
		}
	}

	imports := []string{
		modulePath + "/engine/dialects",
		modulePath + "/builtins/layouts",
		modulePath + "/builtins/sitetemplates",
		modulePath + "/engine/plugins",
		"enginelayouts " + modulePath + "/engine/layouts",
		modulePath + "/engine/session",
	}
	for _, id := range a.Plugins {
		imports = append(imports, modulePath+"/"+pluginPackages[id])
	}
	for _, id := range a.Dialects {
		imports = append(imports, modulePath+"/"+dialectPackages[id])
	}
	slices.SortFunc(imports, func(x, y string) int { return strings.Compare(importPath(x), importPath(y)) })
	imports = append([]string{`"io/fs"`, ""}, imports...) // the standard library first, in a group of its own

	var b bytes.Buffer
	b.WriteString("// Code generated by kit/assembly/cmd/gen from app-assembly.yml; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n", pkg)
	for _, im := range imports {
		if im == `"io/fs"` {
			fmt.Fprintf(&b, "\t%s\n", im)
		} else if im == "" {
			b.WriteString("\n")
		} else if name, path, ok := strings.Cut(im, " "); ok {
			fmt.Fprintf(&b, "\t%s %q\n", name, path)
		} else {
			fmt.Fprintf(&b, "\t%q\n", im)
		}
	}
	b.WriteString(")\n\n")

	b.WriteString("// assemblyPlugins is the registry of the built-in plugins this app includes.\n")
	b.WriteString("func assemblyPlugins() *plugins.Registry {\n\tr := plugins.NewRegistry()\n")
	b.WriteString("\tfor _, p := range []plugins.Plugin{")
	for i, id := range a.Plugins {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(id + ".New()")
	}
	b.WriteString("} {\n\t\tif err := r.Register(p); err != nil {\n\t\t\tpanic(err)\n\t\t}\n\t}\n\treturn r\n}\n\n")

	layoutIDs := a.Layouts
	if len(layoutIDs) == 0 {
		layoutIDs = []string{FallbackLayout} // layouts.Registry without ids means all of them
	}
	b.WriteString("// assemblyLayouts is the registry of the built-in layouts this app includes\n// (article, the fallback, is always there).\n")
	fmt.Fprintf(&b, "func assemblyLayouts(version string) *enginelayouts.Registry {\n\treturn layouts.Registry(version, %s)\n}\n\n", listArgs(layoutIDs))

	b.WriteString("// assemblyTemplates holds the built-in site templates this app includes.\n")
	fmt.Fprintf(&b, "func assemblyTemplates() fs.FS {\n\tf, err := sitetemplates.Sub(%s)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn f\n}\n\n", listArgs(a.Templates))

	b.WriteString("// assemblyDialects is the registry of the markdown dialects this app includes.\n")
	b.WriteString("func assemblyDialects() *dialects.Registry {\n\tr, err := dialects.NewRegistry(")
	for i, id := range a.Dialects {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(id + ".New()")
	}
	b.WriteString(")\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn r\n}\n\n")

	b.WriteString("// assemblyInfo is what the app's build is made of, for the version line and\n// Settings. The add-ons are the ones linked in (build tags), added at run time.\n")
	fmt.Fprintf(&b, "var assemblyInfo = session.BuildInfo{\n\tApp:       %q,\n\tFeatures:  %s,\n\tPlugins:   %s,\n\tLayouts:   %s,\n\tTemplates: %s,\n\tDialects:  %s,\n\tTheme:     %q,\n}\n",
		a.App, stringSlice(a.Features), stringSlice(a.Plugins), stringSlice(withFallback(a.Layouts)), stringSlice(a.Templates), stringSlice(a.Dialects), a.Theme)

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code is not valid Go: %v", err)
	}
	return out, nil
}

// withFallback lists article first when the assembly leaves it out, as the
// registry does.
func withFallback(layouts []string) []string {
	if slices.Contains(layouts, FallbackLayout) {
		return layouts
	}
	return append([]string{FallbackLayout}, layouts...)
}

func importPath(im string) string {
	if _, p, ok := strings.Cut(im, " "); ok {
		return p
	}
	return im
}

// stringSlice writes ids (already validated) as a Go []string literal.
func stringSlice(ids []string) string {
	if len(ids) == 0 {
		return "[]string{}"
	}
	q := make([]string, len(ids))
	for i, id := range ids {
		q[i] = fmt.Sprintf("%q", id)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// listArgs writes ids (already validated) as call arguments: "a", "b".
func listArgs(ids []string) string {
	q := make([]string, len(ids))
	for i, id := range ids {
		q[i] = fmt.Sprintf("%q", id)
	}
	return strings.Join(q, ", ")
}
